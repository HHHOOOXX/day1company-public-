def is_kr_holiday(d):
    """date 객체를 받아 (공휴일 여부, 공휴일명|None)을 반환한다.
    KR_HOLIDAYS_BY_YEAR에 없는 연도면 안전한 쪽(공휴일 아님)으로 처리하되, 목록 갱신을 깜빡했다는
    걸 알아챌 수 있게 콘솔에 경고를 남긴다."""
    year_holidays = KR_HOLIDAYS_BY_YEAR.get(d.year)
    if year_holidays is None:
        print(f"[경고] {d.year}년 공휴일 목록이 config.KR_HOLIDAYS_BY_YEAR에 없습니다 — 갱신이 필요합니다.")
        return False, None
    name = year_holidays.get(d.isoformat())
    return (name is not None), name


